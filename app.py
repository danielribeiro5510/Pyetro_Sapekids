@app.post("/admin/users/<int:user_id>/toggle")
@login_required
@admin_required
def admin_toggle_user(user_id):
    conn = db()
    user = conn.execute(
        "SELECT id, username, role, active FROM users WHERE id = ?",
        (user_id,)
    ).fetchone()

    if not user:
        conn.close()
        flash("Usuário não encontrado.", "danger")
        return redirect(url_for("admin_users"))

    # Proteção absoluta da conta principal.
    if user["username"].lower() == "admin":
        conn.close()
        flash("A conta admin principal não pode ser desativada.", "warning")
        return redirect(url_for("admin_users"))

    # Não permite desativar o próprio usuário logado.
    if int(user["id"]) == int(session.get("user_id")):
        conn.close()
        flash("Você não pode desativar o próprio usuário.", "warning")
        return redirect(url_for("admin_users"))

    new_active = not bool(user["active"])

    # Nunca deixa o sistema ficar sem administrador ativo.
    if new_active == 0 and user["role"] == "admin":
        active_admins = conn.execute(
            "SELECT COUNT(*) AS c FROM users WHERE role = 'admin' AND active = ?",
            (True,)
        ).fetchone()["c"]
        if int(active_admins or 0) <= 1:
            conn.close()
            flash("Não é possível desativar o último administrador ativo.", "warning")
            return redirect(url_for("admin_users"))

    conn.execute(
        "UPDATE users SET active = ? WHERE id = ?",
        (new_active, user_id)
    )
    conn.commit()
    conn.close()

    audit(
        "STATUS DE USUÁRIO",
        f"Usuário {user['username']} -> {'ativo' if new_active else 'desativado'}"
    )
    flash(
        f"Usuário {'ativado' if new_active else 'desativado'} com sucesso.",
        "success"
    )
    return redirect(url_for("admin_users"))


