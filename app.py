def admin_backup():
    import csv, io, zipfile
    tables = ["users","products","movements","sales","sale_items","customers","suppliers","cash_sessions","cash_movements","returns","return_items","categories","audit_logs"]
    mem = io.BytesIO()
    with zipfile.ZipFile(mem, "w", zipfile.ZIP_DEFLATED) as z:
        conn = db()
        for table in tables:
            try:
                rows = conn.execute(f"SELECT * FROM {table} ORDER BY 1").fetchall()
            except Exception:
                continue
            output = io.StringIO()
            writer = csv.writer(output)
            if rows:
                keys = list(rows[0].keys()) if hasattr(rows[0], "keys") else []
                if table == "users" and "password" in keys:
                    keys.remove("password")
                writer.writerow(keys)
                for row in rows:
                    values = [row[k] for k in keys] if hasattr(row, "__getitem__") and hasattr(row, "keys") else list(row)
                    writer.writerow(values)
            else:
                # Cabeçalho conhecido não é essencial; tabela vazia fica identificada.
                writer.writerow(["sem_registros"])
            z.writestr(f"{table}.csv", output.getvalue())
        conn.close()
    mem.seek(0)
    audit("BACKUP", "Backup administrativo exportado em CSV/ZIP")
    return send_file(mem, as_attachment=True,
                     download_name=f"backup_pyetro_{datetime.now(TZ).strftime('%Y%m%d_%H%M%S')}.zip",
                     mimetype="application/zip")


