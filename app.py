@app.post("/sales/<int:sale_id>/delete")
@login_required
@admin_required
def delete_sale(sale_id):
    conn = db()
    try:
        sale = conn.execute(
            "SELECT * FROM sales WHERE id = ?",
            (sale_id,)
        ).fetchone()

        if not sale:
            flash("Venda não encontrada.", "danger")
            return redirect(url_for("sales"))

        items = conn.execute(
            "SELECT * FROM sale_items WHERE sale_id = ?",
            (sale_id,)
        ).fetchall()

        # Reverte o estoque dos itens vendidos.
        for item in items:
            product = conn.execute(
                "SELECT id, stock FROM products WHERE id = ?",
                (item["product_id"],)
            ).fetchone()

            if product:
                conn.execute(
                    "UPDATE products SET stock = ? WHERE id = ?",
                    (product["stock"] + item["quantity"], product["id"])
                )

            conn.execute(
                """DELETE FROM movements
                   WHERE product_id = ? AND type = 'SAIDA'
                     AND note = ?""",
                (item["product_id"], f"Venda #{sale_id}")
            )

        conn.execute("DELETE FROM sale_items WHERE sale_id = ?", (sale_id,))
        conn.execute("DELETE FROM sales WHERE id = ?", (sale_id,))
        conn.commit()

        audit(
            "EXCLUSÃO DE VENDA",
            f"Venda #{sale_id} - estoque dos itens restaurado"
        )
        flash(f"Venda #{sale_id} excluída e estoque restaurado.", "success")

    except Exception as exc:
        conn.rollback()
        flash(f"Não foi possível excluir a venda: {exc}", "danger")
    finally:
        conn.close()

    return redirect(url_for("sales"))


