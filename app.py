class DBWrapper:
    """Small compatibility wrapper so the existing app can use SQLite locally
    or PostgreSQL/Neon in production without changing every query by hand.
    """
    def __init__(self, conn, postgres=False):
        self._conn = conn
        self.postgres = postgres

    def _sql(self, sql):
        if self.postgres:
            # The original app uses SQLite's ? placeholders.
            return sql.replace("?", "%s")
        return sql

    def execute(self, sql, params=None):
        return self._conn.execute(self._sql(sql), params or ())

    def executescript(self, script):
        if not self.postgres:
            return self._conn.executescript(script)

        # PostgreSQL schema used below is already written as separate statements.
        for statement in script.split(";"):
            statement = statement.strip()
            if statement:
                self._conn.execute(statement)

    def commit(self):
        return self._conn.commit()

    def rollback(self):
        return self._conn.rollback()

    def close(self):
        return self._conn.close()


def db():
    if DATABASE_URL:
        if psycopg is None:
            raise RuntimeError(
                "A biblioteca psycopg não está instalada. "
                "Adicione psycopg[binary] ao requirements.txt."
            )
        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        return DBWrapper(conn, postgres=True)

    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    return DBWrapper(conn, postgres=False)


def init_db():
    conn = db()

    if conn.postgres:
        schema = """
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            role TEXT NOT NULL DEFAULT 'admin',
            active BOOLEAN NOT NULL DEFAULT TRUE
        );

        CREATE TABLE IF NOT EXISTS products (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            category TEXT NOT NULL,
            brand TEXT,
            color TEXT,
            size TEXT,
            price DOUBLE PRECISION NOT NULL DEFAULT 0,
            stock INTEGER NOT NULL DEFAULT 0,
            min_stock INTEGER NOT NULL DEFAULT 0,
            created_at TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS movements (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            product_id INTEGER NOT NULL,
            type TEXT NOT NULL,
            quantity INTEGER NOT NULL,
            note TEXT,
            created_at TEXT NOT NULL,
            FOREIGN KEY(product_id) REFERENCES products(id)
        );

        CREATE TABLE IF NOT EXISTS sales (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            total DOUBLE PRECISION NOT NULL DEFAULT 0,
            payment_method TEXT NOT NULL,
            username TEXT NOT NULL,
            created_at TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS sale_items (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sale_id INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            quantity INTEGER NOT NULL,
            unit_price DOUBLE PRECISION NOT NULL,
            subtotal DOUBLE PRECISION NOT NULL,
            FOREIGN KEY(sale_id) REFERENCES sales(id),
            FOREIGN KEY(product_id) REFERENCES products(id)
        );

        CREATE TABLE IF NOT EXISTS audit_logs (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL,
            action TEXT NOT NULL,
            details TEXT,
            created_at TEXT NOT NULL
        );
        """
        conn.executescript(schema)
        # Em bancos PostgreSQL já existentes, a coluna active pode ainda não existir.
        # Verificamos antes de alterar para não abortar a transação.
        col = conn.execute(
            "SELECT 1 FROM information_schema.columns WHERE table_name = ? AND column_name = ?",
            ("users", "active")
        ).fetchone()
        if not col:
            conn.execute("ALTER TABLE users ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE")
        conn.commit()
    else:
        conn.executescript("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            role TEXT NOT NULL DEFAULT 'admin',
            active INTEGER NOT NULL DEFAULT 1
        );

        CREATE TABLE IF NOT EXISTS products (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            category TEXT NOT NULL,
            brand TEXT,
            color TEXT,
            size TEXT,
            price REAL NOT NULL DEFAULT 0,
            stock INTEGER NOT NULL DEFAULT 0,
            min_stock INTEGER NOT NULL DEFAULT 0,
            created_at TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS movements (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            product_id INTEGER NOT NULL,
            type TEXT NOT NULL,
            quantity INTEGER NOT NULL,
            note TEXT,
            created_at TEXT NOT NULL,
            FOREIGN KEY(product_id) REFERENCES products(id)
        );

        CREATE TABLE IF NOT EXISTS sales (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            total REAL NOT NULL DEFAULT 0,
            payment_method TEXT NOT NULL,
            username TEXT NOT NULL,
            created_at TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS sale_items (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            sale_id INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            quantity INTEGER NOT NULL,
            unit_price REAL NOT NULL,
            subtotal REAL NOT NULL,
            FOREIGN KEY(sale_id) REFERENCES sales(id),
            FOREIGN KEY(product_id) REFERENCES products(id)
        );

        CREATE TABLE IF NOT EXISTS audit_logs (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT NOT NULL,
            action TEXT NOT NULL,
            details TEXT,
            created_at TEXT NOT NULL
        );
        """)

    # Cria somente usuários que ainda não existem.
    # Depois do primeiro cadastro, senha, perfil e status são administrados
    # pela tela de Usuários e não são sobrescritos no deploy.
    seed_users = os.environ.get(
        "SEED_USERS",
        "admin:admin123,Pedro:Pyetro123,Roberta:Pyetro123"
    )

    for item in seed_users.split(","):
        item = item.strip()
        if not item:
            continue
        try:
            username, senha = item.split(":", 1)
        except ValueError:
            continue

        username = username.strip()
        senha = senha.strip()
        if not username or not senha:
            continue

        existente = conn.execute(
            "SELECT id FROM users WHERE LOWER(username) = LOWER(?)",
            (username,)
        ).fetchone()

        if not existente:
            role = "admin" if username.lower() == "admin" else "operator"
            conn.execute(
                "INSERT INTO users (username, password, role, active) VALUES (?, ?, ?, ?)",
                (username, generate_password_hash(senha), role, True)
            )

    # A conta principal "admin" sempre permanece administradora e ativa.
    conn.execute(
        "UPDATE users SET role = 'admin', active = ? WHERE LOWER(username) = 'admin'",
        (True,)
    )

    # Corrige registros antigos que não tenham active.
    conn.execute("UPDATE users SET active = ? WHERE active IS NULL", (True,))

    conn.commit()
    conn.close()


try:
    init_db()
except Exception as exc:
    # Keep the Render log explicit instead of hiding the real startup error.
    raise RuntimeError(f"Falha ao inicializar o banco: {exc}") from exc


def login_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if "user_id" not in session:
            return redirect(url_for("login"))
        return fn(*args, **kwargs)
    return wrapper


@app.before_request
def refresh_logged_user():
    """Sincroniza a sessão com o usuário real do banco em toda requisição.

    Isso evita que uma página reutilize um nome/role antigo da sessão.
    O usuário é sempre identificado pelo user_id gravado no login.
    """
    user_id = session.get("user_id")
    if not user_id:
        return None

    conn = None
    try:
        conn = db()
        user = conn.execute(
            "SELECT id, username, role, active FROM users WHERE id = ?",
            (user_id,)
        ).fetchone()
    except Exception:
        user = None
    finally:
        if conn is not None:
            conn.close()

    if not user:
        session.clear()
        return None

    # PostgreSQL usa BOOLEAN e SQLite usa 0/1; bool() funciona nos dois.
    if not bool(user["active"]):
        session.clear()
        return None

    session["username"] = user["username"]
    session["role"] = user["role"]
    return None


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        username = request.form["username"].strip()
        password = request.form["password"]

        # Remove qualquer sessão anterior antes de iniciar a nova.
        session.clear()

        conn = db()
        user = conn.execute(
            "SELECT * FROM users WHERE username = ?",
            (username,)
        ).fetchone()
        conn.close()

        if user and not bool(user["active"]):
            flash("Este usuário está desativado. Procure o administrador.", "danger")
            return render_template("login.html")

        if user and check_password_hash(user["password"], password):
            session["user_id"] = user["id"]
            session["username"] = user["username"]
            session["role"] = user["role"]
            if user["role"] == "admin":
                return redirect(url_for("admin_dashboard"))
            return redirect(url_for("dashboard"))

        flash("Usuário ou senha inválidos.", "danger")

    return render_template("login.html")


