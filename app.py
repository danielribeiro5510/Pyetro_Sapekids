@app.route("/sales/<int:sale_id>/return",methods=["GET","POST"])
@login_required
@admin_required
def return_sale(sale_id):
    conn=db(); sale=conn.execute("SELECT * FROM sales WHERE id=?",(sale_id,)).fetchone()
    if not sale: conn.close(); return "Venda não encontrada",404
    items=conn.execute("SELECT si.*,p.name,p.stock FROM sale_items si JOIN products p ON p.id=si.product_id WHERE si.sale_id=?",(sale_id,)).fetchall()
    if request.method=="POST":
        try:
            sale_item_id=int(request.form.get("sale_item_id")); qty=int(request.form.get("quantity") or 0); replacement_id=int(request.form.get("replacement_product_id") or 0) or None; replacement_qty=int(request.form.get("replacement_quantity") or 0); typ=request.form.get("type","DEVOLUCAO")
            si=conn.execute("SELECT * FROM sale_items WHERE id=? AND sale_id=?",(sale_item_id,sale_id)).fetchone()
            already=conn.execute("SELECT COALESCE(SUM(quantity),0) q FROM return_items WHERE sale_item_id=?",(sale_item_id,)).fetchone()["q"]
            if not si or qty<=0 or qty>int(si["quantity"] or 0)-int(already or 0): raise ValueError("Quantidade de devolução inválida ou já devolvida.")
            if replacement_id and replacement_qty<=0: raise ValueError("Informe a quantidade da troca.")
            if replacement_id:
                rp=conn.execute("SELECT * FROM products WHERE id=?",(replacement_id,)).fetchone()
                if not rp or rp["stock"]<replacement_qty: raise ValueError("Estoque insuficiente para o produto de troca.")
            else: rp=None; replacement_qty=0
            original_value=float(si["unit_price"])*qty; replacement_value=float(rp["price"])*replacement_qty if rp else 0; difference=round(replacement_value-original_value,2)
            now=datetime.now(TZ).strftime("%Y-%m-%d %H:%M:%S"); user=get_current_user()["username"]
            cur=conn.execute("INSERT INTO returns (sale_id,type,reason,difference,username,created_at) VALUES (?,?,?,?,?,?)" + (" RETURNING id" if conn.postgres else ""),(sale_id,typ,request.form.get("reason","").strip(),difference,user,now)); rid=cur.fetchone()["id"] if conn.postgres else cur.lastrowid
            conn.execute("INSERT INTO return_items (return_id,sale_item_id,product_id,quantity,replacement_product_id,replacement_quantity) VALUES (?,?,?,?,?,?)",(rid,sale_item_id,si["product_id"],qty,replacement_id,replacement_qty))
            conn.execute("UPDATE products SET stock=stock+? WHERE id=?",(qty,si["product_id"]))
            conn.execute("INSERT INTO movements (product_id,type,quantity,note,created_at) VALUES (?,?,?,?,?)",(si["product_id"],"ENTRADA",qty,f"Devolução Venda #{dict(sale).get('sale_number') or sale_id}",now))
            if rp:
                conn.execute("UPDATE products SET stock=stock-? WHERE id=?",(replacement_qty,replacement_id)); conn.execute("INSERT INTO movements (product_id,type,quantity,note,created_at) VALUES (?,?,?,?,?)",(replacement_id,"SAIDA",replacement_qty,f"Troca Venda #{dict(sale).get('sale_number') or sale_id}",now))
            if difference < 0 and sale["payment_method"] == "Dinheiro" and sale["cash_session_id"]:
                conn.execute("INSERT INTO cash_movements (cash_session_id,type,amount,description,username,created_at) VALUES (?,?,?,?,?,?)",(sale["cash_session_id"],"SANGRIA",abs(difference),f"Reembolso devolução Venda #{dict(sale).get('sale_number') or sale_id}",user,now))
            elif difference > 0 and sale["cash_session_id"] and sale["payment_method"] == "Dinheiro":
                conn.execute("INSERT INTO cash_movements (cash_session_id,type,amount,description,username,created_at) VALUES (?,?,?,?,?,?)",(sale["cash_session_id"],"SUPRIMENTO",difference,f"Recebimento diferença troca Venda #{dict(sale).get('sale_number') or sale_id}",user,now))
            conn.commit(); conn.close(); audit("DEVOLUÇÃO/TROCA",f"Venda #{dict(sale).get('sale_number') or sale_id} - diferença R$ {difference:.2f}"); flash(f"Operação registrada. Diferença: R$ {difference:.2f}.","success"); return redirect(url_for("sale_detail",sale_id=sale_id))
        except Exception as exc: conn.rollback(); flash(str(exc),"danger")
    products=conn.execute("SELECT id,name,price,stock FROM products WHERE stock>0 ORDER BY name").fetchall(); conn.close(); return render_template("return_sale.html",sale=sale,items=items,products=products)

