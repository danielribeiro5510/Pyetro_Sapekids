def parse_money(value, default=0.0):
    """Parse monetary input in Brazilian or standard notation.

    59.99 -> 59.99
    59,99 -> 59.99
    1.399,99 -> 1399.99
    1,399.99 -> 1399.99
    """
    try:
        text = str(value if value is not None else default).strip()
        text = text.replace("R$", "").replace(" ", "")
        if not text:
            return float(default)
        if "," in text and "." in text:
            if text.rfind(",") > text.rfind("."):
                text = text.replace(".", "").replace(",", ".")
            else:
                text = text.replace(",", "")
        elif "," in text:
            text = text.replace(",", ".")
        return float(text)
    except (ValueError, TypeError):
        try:
            return float(value or default)
        except (ValueError, TypeError):
            return float(default)

def table_columns(conn, table):
    if conn.postgres:
        return {r["column_name"] for r in conn.execute("SELECT column_name FROM information_schema.columns WHERE table_name = ?", (table,)).fetchall()}
    return {r[1] for r in conn.execute(f"PRAGMA table_info({table})").fetchall()}

def add_column_if_missing(conn, table, column, definition):
    if column not in table_columns(conn, table):
        conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")

