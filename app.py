@login_required
def sales():
    conn = db()
    rows = conn.execute("""
        SELECT s.*, COUNT(si.id) AS item_count,
               COALESCE(c.name, '') AS customer_name
        FROM sales s
        LEFT JOIN sale_items si ON si.sale_id = s.id
        LEFT JOIN customers c ON c.id = s.customer_id
        WHERE s.status <> 'CANCELLED'
        GROUP BY s.id, c.name
        ORDER BY s.id ASC
    """).fetchall()
    # display_number é a sequência atual das vendas existentes.
    # Assim, se uma venda for excluída, não ficam buracos na numeração exibida.
    display_rows = []
    total_rows = len(rows)
    for index, row in enumerate(rows, start=1):
        data = dict(row)
        data["display_number"] = index
        data["status"] = data.get("status", "COMPLETED")
        display_rows.append(data)
    display_rows.reverse()
    conn.close()
    return render_template("sales.html", sales=display_rows)


@app.route("/sales/new", methods=["GET", "POST"])
@login_required
def new_sale():
    cart = session.get("sale_cart", [])

    if request.method == "POST":
        action = request.form.get("action")

        if action == "clear":
            session.pop("sale_cart", None)
            flash("Venda limpa.", "info")
            return redirect(url_for("new_sale"))

        if action == "add":
            try:
                product_id = int(request.form.get("product_id") or 0)
                quantity = int(request.form.get("quantity") or 0)
            except (ValueError, TypeError):
                flash("Selecione um produto e informe uma quantidade válida.", "danger")
                return redirect(url_for("new_sale"))
            if quantity <= 0:
                flash("A quantidade deve ser maior que zero.", "danger")
                return redirect(url_for("new_sale"))

            conn = db()
            barcode = request.form.get("barcode", "").strip()
            if barcode:
                product = conn.execute("SELECT * FROM products WHERE barcode = ? LIMIT 1", (barcode,)).fetchone()
            else:
                product = conn.execute("SELECT * FROM products WHERE id = ?", (product_id,)).fetchone()
            conn.close()
            if not product:
                flash("Produto não encontrado.", "danger")
                return redirect(url_for("new_sale"))

            product_id = int(product["id"]); existing_qty = next((i["quantity"] for i in cart if i["product_id"] == product_id), 0)
            if existing_qty + quantity > product["stock"]:
                flash(f"Estoque insuficiente. Disponível: {product['stock']}.", "danger")
                return redirect(url_for("new_sale"))

            found = False
            for item in cart:
                if item["product_id"] == product_id:
                    item["quantity"] += quantity
                    found = True
                    break
            if not found:
                cart.append({
                    "product_id": product["id"], "name": product["name"],
                    "category": product["category"], "brand": product["brand"] or "",
                    "color": product["color"] or "", "size": product["size"] or "",
                    "quantity": quantity, "unit_price": float(product["price"])
                })
            session["sale_cart"] = cart
            return redirect(url_for("new_sale"))

        if action == "remove":
            try:
                product_id = int(request.form["product_id"])
                cart = [i for i in cart if i["product_id"] != product_id]
                session["sale_cart"] = cart
            except (ValueError, TypeError):
                pass
            return redirect(url_for("new_sale"))

        if action == "finish":
            if not cart:
                flash("Adicione pelo menos um produto à venda.", "danger")
                return redirect(url_for("new_sale"))

            payment_method = request.form.get("payment_method", "").strip()
            allowed = {"PIX", "Dinheiro", "Cartão de débito", "Cartão de crédito"}
            if payment_method not in allowed:
                flash("Selecione uma forma de pagamento.", "danger")
                return redirect(url_for("new_sale"))

            try:
                # Aceita tanto 10.5 quanto 10,5 no padrão brasileiro.
                discount_raw = (request.form.get("discount_percent") or "0").strip().replace(",", ".")
                discount_percent = float(discount_raw)
            except (ValueError, TypeError):
                discount_percent = 0
            if discount_percent < 0 or discount_percent > 100:
                flash("O desconto deve estar entre 0% e 100%.", "danger")
                return redirect(url_for("new_sale"))

            customer_id_raw = request.form.get("customer_id", "").strip()
            customer_id = None
            if customer_id_raw:
                try:
                    customer_id = int(customer_id_raw)
                except ValueError:
                    flash("Cliente inválido.", "danger")
                    return redirect(url_for("new_sale"))

            conn = db()
            try:
                if customer_id is not None:
                    customer = conn.execute("SELECT id FROM customers WHERE id = ?", (customer_id,)).fetchone()
                    if not customer:
                        raise ValueError("Cliente não encontrado.")

                checked = []
                subtotal_total = 0.0
                for item in cart:
                    product = conn.execute("SELECT * FROM products WHERE id = ?", (item["product_id"],)).fetchone()
                    if not product:
                        raise ValueError(f"Produto '{item['name']}' não existe mais.")
                    if item["quantity"] > product["stock"]:
                        raise ValueError(f"Estoque insuficiente para '{product['name']}'. Disponível: {product['stock']}.")
                    unit_price = float(product["price"])
                    subtotal = unit_price * item["quantity"]
                    subtotal_total += subtotal
                    checked.append((product, item["quantity"], unit_price, subtotal))

                discount_value = subtotal_total * (discount_percent / 100.0)
                total = round(subtotal_total - discount_value, 2)
                now = datetime.now(TZ).strftime("%Y-%m-%d %H:%M:%S")
                username = get_current_user()["username"] if get_current_user() else "admin"
                open_cash = conn.execute(
                    "SELECT id FROM cash_sessions WHERE status='OPEN' ORDER BY id DESC LIMIT 1"
                ).fetchone()
                cash_session_id = open_cash["id"] if open_cash else None

                # Número visível da venda. O ID interno nunca é reutilizado.
                # Se todas as vendas forem excluídas, a próxima começa novamente em #1.
                # Número visível: sequência das vendas que realmente existem.
                # O ID interno do banco continua independente e nunca é reutilizado.
                current_sales_count = conn.execute(
                    "SELECT COUNT(*) AS n FROM sales WHERE status <> 'CANCELLED'"
                ).fetchone()["n"]
                sale_number = int(current_sales_count or 0) + 1

                sale_token = (request.form.get("sale_token") or session.get("sale_form_token") or "").strip()
                if not sale_token:
                    sale_token = secrets.token_urlsafe(24)

                if conn.postgres:
                    cur = conn.execute(
                        """INSERT INTO sales (total, subtotal, discount_percent, customer_id, payment_method, username, created_at, cash_session_id, sale_number, sale_token, status)
                           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'COMPLETED') RETURNING id""",
                        (total, subtotal_total, discount_percent, customer_id, payment_method, username, now, cash_session_id, sale_number, sale_token)
                    )
                    sale_id = cur.fetchone()["id"]
                else:
                    cur = conn.execute(
                        """INSERT INTO sales (total, subtotal, discount_percent, customer_id, payment_method, username, created_at, cash_session_id, sale_number, sale_token, status)
                           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'COMPLETED')""",
                        (total, subtotal_total, discount_percent, customer_id, payment_method, username, now, cash_session_id, sale_number, sale_token)
                    )
                    sale_id = cur.lastrowid

                for product, quantity, unit_price, item_subtotal in checked:
                    conn.execute(
                        """INSERT INTO sale_items (sale_id, product_id, quantity, unit_price, unit_cost, subtotal)
                           VALUES (?, ?, ?, ?, ?, ?)""",
                        (sale_id, product["id"], quantity, unit_price, float(product.get("cost",0) if hasattr(product, "get") else product["cost"] or 0), item_subtotal)
                    )
                    conn.execute("UPDATE products SET stock = ? WHERE id = ?", (product["stock"] - quantity, product["id"]))
                    conn.execute(
                        """INSERT INTO movements (product_id, type, quantity, note, created_at)
                           VALUES (?, ?, ?, ?, ?)""",
                        (product["id"], "SAIDA", quantity, f"Venda #{sale_number}", now)
                    )

                conn.commit()
                audit("NOVA VENDA", f"Venda #{sale_number} - Subtotal R$ {subtotal_total:.2f} - Desconto {discount_percent:.2f}% - Total R$ {total:.2f}")
                session.pop("sale_cart", None)
                session.pop("sale_form_token", None)
                flash(f"Venda #{sale_number} finalizada com sucesso.", "success")
                return redirect(url_for("sale_detail", sale_id=sale_id))
            except Exception as exc:
                conn.rollback()
                # Protege contra duplo clique/reenvio: o mesmo token de venda só pode ser processado uma vez.
                try:
                    existing = conn.execute("SELECT id, sale_number FROM sales WHERE sale_token = ? LIMIT 1", (sale_token,)).fetchone()
                except Exception:
                    existing = None
                if existing:
                    session.pop("sale_form_token", None)
                    flash(f"Venda #{existing['sale_number'] or existing['id']} já foi finalizada. O segundo clique foi ignorado.", "info")
                    return redirect(url_for("sale_detail", sale_id=existing["id"]))
                flash(str(exc), "danger")
                return redirect(url_for("new_sale"))
            finally:
                conn.close()

    conn = db()
    products = conn.execute("SELECT * FROM products WHERE stock > 0 ORDER BY name, brand, color, size").fetchall()
    customers = conn.execute("SELECT * FROM customers ORDER BY name").fetchall()
    open_cash = conn.execute("SELECT * FROM cash_sessions WHERE status='OPEN' ORDER BY id DESC LIMIT 1").fetchone()
    conn.close()
    subtotal = sum(i["quantity"] * i["unit_price"] for i in cart)
    if not session.get("sale_form_token"):
        session["sale_form_token"] = secrets.token_urlsafe(24)
    return render_template("new_sale.html", products=products, customers=customers, cart=cart, total=subtotal, subtotal=subtotal, open_cash=open_cash, sale_form_token=session["sale_form_token"])


@app.route("/sales/<int:sale_id>")
@login_required
def sale_detail(sale_id):
    """Exibe uma venda de forma compatível com bancos antigos e novos.

    Se uma instalação antiga ainda não tiver alguma coluna opcional de clientes/desconto,
    a venda continua sendo aberta usando os dados básicos, em vez de gerar HTTP 500.
    """
    conn = db()
    try:
        try:
            sale = conn.execute("""
                SELECT s.*,
                       COALESCE(c.name, '') AS customer_name,
                       COALESCE(c.cpf, '') AS customer_cpf,
                       COALESCE(c.phone, '') AS customer_phone
                FROM sales s
                LEFT JOIN customers c ON c.id = s.customer_id
                WHERE s.id = ?
            """, (sale_id,)).fetchone()
        except Exception:
            conn.rollback()
            sale = conn.execute("""
                SELECT s.*, '' AS customer_name, '' AS customer_cpf, '' AS customer_phone
                FROM sales s WHERE s.id = ?
            """, (sale_id,)).fetchone()

        if not sale:
            return "Venda não encontrada", 404

        items = conn.execute("""
            SELECT si.*, p.name, p.category, p.brand, p.color, p.size
            FROM sale_items si
            LEFT JOIN products p ON p.id = si.product_id
            WHERE si.sale_id = ?
            ORDER BY si.id
        """, (sale_id,)).fetchall()

        # Normaliza campos opcionais para o template.
        sale_data = dict(sale)
        # Número exibido é baseado na posição atual da venda entre as vendas existentes.
        # Isso evita mostrar o ID interno (ex.: /sales/14) como "Venda #14".
        display_row = conn.execute(
            "SELECT COUNT(*) AS n FROM sales WHERE id <= ? AND status <> 'CANCELLED' ", (sale_id,)
        ).fetchone()
        sale_data["display_number"] = int(sale_data.get("sale_number") or (display_row["n"] if display_row else 1) or 1)
        sale_data.setdefault("subtotal", sale_data.get("total", 0) or 0)
        sale_data.setdefault("discount_percent", 0)
        sale_data.setdefault("customer_name", "")
        sale_data.setdefault("customer_cpf", "")
        sale_data.setdefault("customer_phone", "")

        item_data = []
        for item in items:
            d = dict(item)
            d.setdefault("name", "Produto removido")
            d.setdefault("brand", "")
            d.setdefault("color", "")
            d.setdefault("size", "")
            d.setdefault("unit_price", 0)
            d.setdefault("subtotal", 0)
            item_data.append(d)

        return render_template("sale_detail.html", sale=sale_data, items=item_data)
    except Exception as exc:
        conn.rollback()
        app.logger.exception("Erro ao abrir venda #%s", sale_id)
        flash("Não foi possível abrir os detalhes desta venda. A venda permanece registrada.", "danger")
        return redirect(url_for("sales"))
    finally:
        conn.close()


