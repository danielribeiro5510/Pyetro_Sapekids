class DBWrapper:
    """Small compatibility wrapper so the existing app can use SQLite locally
    or PostgreSQL/Neon in production without changing every query by hand.
    """
    def __init__(self, conn, postgres=False):
        self._conn = conn
        self.postgres = postgres

    def _sql(self, sql):
        if self.postgres:
            # The original app uses SQLite's ? placeholders.
            return sql.replace("?", "%s")
        return sql

    def execute(self, sql, params=None):
        return self._conn.execute(self._sql(sql), params or ())

    def executescript(self, script):
        if not self.postgres:
            return self._conn.executescript(script)

        # PostgreSQL schema used below is already written as separate statements.
        for statement in script.split(";"):
            statement = statement.strip()
            if statement:
                self._conn.execute(statement)

    def commit(self):
        return self._conn.commit()

    def rollback(self):
        return self._conn.rollback()

    def close(self):
        return self._conn.close()


def db():
    if DATABASE_URL:
        if psycopg is None:
            raise RuntimeError(
                "A biblioteca psycopg não está instalada. "
                "Adicione psycopg[binary] ao requirements.txt."
            )
        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        return DBWrapper(conn, postgres=True)

    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    return DBWrapper(conn, postgres=False)


def init_db():
    conn = db()

    if conn.postgres:
        schema = """
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            role TEXT NOT NULL DEFAULT 'admin'
        );

        CREATE TABLE IF NOT EXISTS products (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            category TEXT NOT NULL,
            brand TEXT,
            color TEXT,
            size TEXT,
            price DOUBLE PRECISION NOT NULL DEFAULT 0,
            stock INTEGER NOT NULL DEFAULT 0,
            min_stock INTEGER NOT NULL DEFAULT 0,
            created_at TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS movements (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            product_id INTEGER NOT NULL,
            type TEXT NOT NULL,
            quantity INTEGER NOT NULL,
            note TEXT,
            created_at TEXT NOT NULL,
            FOREIGN KEY(product_id) REFERENCES products(id)
        );

        CREATE TABLE IF NOT EXISTS sales (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            total DOUBLE PRECISION NOT NULL DEFAULT 0,
            payment_method TEXT NOT NULL,
            username TEXT NOT NULL,
            created_at TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS sale_items (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sale_id INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            quantity INTEGER NOT NULL,
            unit_price DOUBLE PRECISION NOT NULL,
            subtotal DOUBLE PRECISION NOT NULL,
            FOREIGN KEY(sale_id) REFERENCES sales(id),
            FOREIGN KEY(product_id) REFERENCES products(id)
        );
        """
        conn.executescript(schema)
    else:
        conn.executescript("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            role TEXT NOT NULL DEFAULT 'admin'
        );

        CREATE TABLE IF NOT EXISTS products (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            category TEXT NOT NULL,
            brand TEXT,
            color TEXT,
            size TEXT,
            price REAL NOT NULL DEFAULT 0,
            stock INTEGER NOT NULL DEFAULT 0,
            min_stock INTEGER NOT NULL DEFAULT 0,
            created_at TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS movements (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            product_id INTEGER NOT NULL,
            type TEXT NOT NULL,
            quantity INTEGER NOT NULL,
            note TEXT,
            created_at TEXT NOT NULL,
            FOREIGN KEY(product_id) REFERENCES products(id)
        );

        CREATE TABLE IF NOT EXISTS sales (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            total REAL NOT NULL DEFAULT 0,
            payment_method TEXT NOT NULL,
            username TEXT NOT NULL,
            created_at TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS sale_items (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            sale_id INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            quantity INTEGER NOT NULL,
            unit_price REAL NOT NULL,
            subtotal REAL NOT NULL,
            FOREIGN KEY(sale_id) REFERENCES sales(id),
            FOREIGN KEY(product_id) REFERENCES products(id)
        );
        """)


    # Migrações leves e compatíveis com SQLite/PostgreSQL.
    def ensure_column(table, column, definition):
        if conn.postgres:
            exists = conn.execute(
                """SELECT 1 FROM information_schema.columns
                   WHERE table_name = ? AND column_name = ?""",
                (table, column)
            ).fetchone()
        else:
            exists = conn.execute(
                "SELECT 1 FROM pragma_table_info(?) WHERE name = ?",
                (table, column)
            ).fetchone()
        if not exists:
            conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")

    ensure_column("users", "active", "BOOLEAN NOT NULL DEFAULT TRUE" if conn.postgres else "INTEGER NOT NULL DEFAULT 1")
    ensure_column("products", "sku", "TEXT")
    ensure_column("products", "barcode", "TEXT")
    ensure_column("products", "cost_price", "DOUBLE PRECISION NOT NULL DEFAULT 0" if conn.postgres else "REAL NOT NULL DEFAULT 0")
    ensure_column("products", "active", "BOOLEAN NOT NULL DEFAULT TRUE" if conn.postgres else "INTEGER NOT NULL DEFAULT 1")
    ensure_column("sales", "customer_id", "INTEGER")

    conn.execute("""CREATE TABLE IF NOT EXISTS customers (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        phone TEXT,
        email TEXT,
        notes TEXT,
        created_at TEXT NOT NULL
    )""" if conn.postgres else """CREATE TABLE IF NOT EXISTS customers (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        phone TEXT,
        email TEXT,
        notes TEXT,
        created_at TEXT NOT NULL
    )""")
    conn.execute("""CREATE TABLE IF NOT EXISTS audit_logs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL,
        action TEXT NOT NULL,
        details TEXT,
        created_at TEXT NOT NULL
    )""" if conn.postgres else """CREATE TABLE IF NOT EXISTS audit_logs (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        username TEXT NOT NULL,
        action TEXT NOT NULL,
        details TEXT,
        created_at TEXT NOT NULL
    )""")
    conn.execute("""CREATE TABLE IF NOT EXISTS settings (
        key TEXT PRIMARY KEY,
        value TEXT
    )""")

    # Usuários iniciais: somente cria novos usuários. Nunca sobrescreve
    # senha, função ou status de quem já existe no Neon.
    seed_users = os.environ.get(
        "SEED_USERS",
        "admin:admin123,Pedro:Pyetro123,Roberta:Pyetro123"
    )
    for item in seed_users.split(","):
        item = item.strip()
        if not item:
            continue
        try:
            username, senha = item.split(":", 1)
        except ValueError:
            continue
        username, senha = username.strip(), senha.strip()
        if not username or not senha:
            continue
        role = "admin" if username.lower() == "admin" else "operator"
        existente = conn.execute("SELECT id FROM users WHERE username = ?", (username,)).fetchone()
        if not existente:
            conn.execute(
                "INSERT INTO users (username, password, role, active) VALUES (?, ?, ?, ?)",
                (username, generate_password_hash(senha), role, True if conn.postgres else 1)
            )

    # Garante que a conta admin inicial continue sendo ADM.
    conn.execute("UPDATE users SET role = 'admin', active = ? WHERE LOWER(username) = 'admin'",
                 (True if conn.postgres else 1,))
    conn.commit()
    conn.close()


try:
    init_db()
except Exception as exc:
    # Keep the Render log explicit instead of hiding the real startup error.
    raise RuntimeError(f"Falha ao inicializar o banco: {exc}") from exc


def login_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if "user_id" not in session:
            return redirect(url_for("login"))
        return fn(*args, **kwargs)
    return wrapper


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        username = request.form["username"].strip()
        password = request.form["password"]

        conn = db()
        user = conn.execute(
            "SELECT * FROM users WHERE username = ?",
            (username,)
        ).fetchone()
        conn.close()

        if user and bool(user["active"]) and check_password_hash(user["password"], password):
            session["user_id"] = user["id"]
            session["username"] = user["username"]
            session["role"] = user["role"]
            audit("LOGIN", f"Login realizado como {user['role']}")
            if user["role"] == "admin":
                return redirect(url_for("admin_dashboard"))
            return redirect(url_for("dashboard"))

        if user and not bool(user["active"]):
            flash("Usuário desativado. Procure um administrador.", "danger")
        else:
            flash("Usuário ou senha inválidos.", "danger")

    return render_template("login.html")


