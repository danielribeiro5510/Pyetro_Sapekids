def audit(action, details=""):
    """Registra ações administrativas e operacionais sem armazenar senhas."""
    try:
        conn = db()
        conn.execute(
            "INSERT INTO audit_logs (username, action, details, created_at) VALUES (?, ?, ?, ?)",
            (
                session.get("username", "sistema"),
                action,
                details[:1000],
                datetime.now(TZ).strftime("%Y-%m-%d %H:%M:%S")
            )
        )
        conn.commit()
        conn.close()
    except Exception:
        # Auditoria nunca deve derrubar uma operação principal.
        pass


