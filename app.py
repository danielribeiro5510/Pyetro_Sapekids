@app.post("/products/<int:product_id>/delete")
@login_required
@admin_required
def delete_product(product_id):
    """Exclui um produto sem quebrar o histórico de vendas."""
    conn = db()

    try:
        product = conn.execute(
            "SELECT id, name FROM products WHERE id = ?",
            (product_id,)
        ).fetchone()

        if not product:
            flash("Produto não encontrado.", "danger")
            return redirect(url_for("products"))

        # Produtos que já foram vendidos permanecem no cadastro para
        # preservar o histórico e os relatórios de vendas.
        sold = conn.execute(
            "SELECT COUNT(*) AS c FROM sale_items WHERE product_id = ?",
            (product_id,)
        ).fetchone()

        if int(sold["c"] or 0) > 0:
            flash(
                f"Não é possível excluir '{product['name']}' porque ele já "
                "está vinculado a uma venda. O histórico de vendas foi preservado.",
                "warning"
            )
            return redirect(url_for("products"))

        # Se nunca foi vendido, remove os movimentos e o produto.
        conn.execute(
            "DELETE FROM movements WHERE product_id = ?",
            (product_id,)
        )
        conn.execute(
            "DELETE FROM products WHERE id = ?",
            (product_id,)
        )

        conn.commit()
        audit("EXCLUSÃO DE PRODUTO", f"Produto #{product_id} - {product['name']}")
        flash(f"Produto '{product['name']}' excluído com sucesso.", "success")

    except Exception as exc:
        conn.rollback()
        flash(f"Não foi possível excluir o produto: {exc}", "danger")

    finally:
        conn.close()

    return redirect(url_for("products"))


@app.route("/stock/<int:product_id>", methods=["GET", "POST"])
@login_required
def stock(product_id):
    conn = db()

    product = conn.execute(
        "SELECT * FROM products WHERE id = ?",
        (product_id,)
    ).fetchone()

    if not product:
        conn.close()
        return "Produto não encontrado", 404

    if request.method == "POST":
        movement_type = request.form["type"]
        quantity = int(request.form["quantity"])
        note = request.form.get("note", "").strip()

        if quantity <= 0:
            flash("A quantidade deve ser maior que zero.", "danger")

        elif movement_type == "SAIDA" and quantity > product["stock"]:
            flash("Estoque insuficiente para essa saída.", "danger")

        else:
            if movement_type == "ENTRADA":
                new_stock = product["stock"] + quantity
            else:
                new_stock = product["stock"] - quantity

            conn.execute(
                "UPDATE products SET stock = ? WHERE id = ?",
                (new_stock, product_id)
            )

            conn.execute("""
                INSERT INTO movements
                (product_id, type, quantity, note, created_at)
                VALUES (?, ?, ?, ?, ?)
            """, (
                product_id,
                movement_type,
                quantity,
                note,
                datetime.now(TZ).strftime("%Y-%m-%d %H:%M:%S")
            ))

            conn.commit()
            conn.close()

            flash(f"{movement_type.title()} registrada com sucesso.", "success")
            return redirect(url_for("stock", product_id=product_id))

    movements = conn.execute("""
        SELECT * FROM movements
        WHERE product_id = ?
        ORDER BY id DESC
    """, (product_id,)).fetchall()

    conn.close()

    return render_template(
        "stock.html",
        product=product,
        movements=movements
    )


